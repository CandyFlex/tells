/**
 * build-docs-data.mjs: generate docs/data.js and stamp the computed regions
 * of docs/index.html and docs/rules.html.
 *
 *   node scripts/build-docs-data.mjs           write both
 *   node scripts/build-docs-data.mjs --check   exit 1 if either is stale
 *   node scripts/build-docs-data.mjs --npm     ask the registry whether the
 *                                              package is published, record
 *                                              the answer, then write both
 *
 * Deterministic and offline, except --npm, which is the only network call
 * and writes its answer to scripts/npm-status.json so every later build can
 * read it without a network. The page may show no figure that is not in
 * data.js or computed in the browser by docs/lib. data.js carries:
 *
 *   sample       the machine About page, with its provenance, for the page to
 *                lint on load (the highlights are the program's, not typed)
 *   humanSample  the opening paragraphs of a public-domain text in the corpus
 *   corpus       corpus/results.json, as observed
 *   facts        what the corpus table shows, as numbers (the same function
 *                writes the README sentences)
 *   manifest     per-file title, kind, author, date and licence (no prompts
 *                beyond the sample's; the full manifest stays in the repo)
 *   caveat       the corpus caveat, verbatim
 *   inSample     the README's in-sample disclosure, verbatim
 *   npm          whether the package is on npm, and when that was checked
 *
 * index.html and rules.html hold their computed parts between
 * <!-- gen:name --> and <!-- /gen:name --> markers. They are rendered by docs/page.mjs, the same
 * functions the browser runs, using the copy of the linter in docs/lib.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execSync } from 'node:child_process';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { VERSION } from '../src/report.mjs';
import { corpusFacts } from './build-readme.mjs';
import { analyze } from '../docs/lib/index.mjs';
import * as page from '../docs/page.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const NPM_STATUS = join(ROOT, 'scripts', 'npm-status.json');
const HUMAN_SAMPLE_ID = 'twain-german';
const HUMAN_SAMPLE_MIN_WORDS = 300;
const FIXED = { observedAt: '2026-09-19T00:00:00.000Z' };

const read = (...p) => readFileSync(join(ROOT, ...p), 'utf8').replace(/\r\n?/g, '\n');

/** Whole paragraphs from the top of a text until it is long enough for rates to be reliable. */
function opening(text, minWords) {
  const out = [];
  let words = 0;
  for (const para of text.split(/\n{2,}/)) {
    if (!para.trim()) continue;
    out.push(para.trim());
    words += para.trim().split(/\s+/).length;
    if (words >= minWords) break;
  }
  return `${out.join('\n\n')}\n`;
}

export function buildData() {
  const manifest = JSON.parse(read('corpus', 'MANIFEST.json'));
  const corpus = JSON.parse(read('corpus', 'results.json'));
  const pkg = JSON.parse(read('package.json'));
  const about = manifest.files.find((f) => f.id === 'about-us');
  const human = manifest.files.find((f) => f.id === HUMAN_SAMPLE_ID);
  const inSample = read('README.md').split('\n').find((l) => l.startsWith('**The rates below are in-sample.**'));
  if (!inSample) throw new Error('README.md no longer has the in-sample disclosure paragraph');

  return {
    version: VERSION,
    packageName: pkg.name,
    repository: pkg.repository.url,
    node: pkg.engines.node,
    generatedFrom: ['corpus/MANIFEST.json', 'corpus/results.json', `corpus/${about.path}`, `corpus/${human.path}`, 'README.md', 'package.json', 'scripts/npm-status.json'],
    sample: {
      id: about.id,
      text: read('corpus', about.path),
      model: about.model,
      generatedOn: about.generatedOn,
      prompt: about.prompt,
      caption: `Sample written by ${about.model} on ${about.generatedOn} for this corpus; prompt in corpus/MANIFEST.json.`,
    },
    humanSample: {
      id: human.id,
      text: opening(read('corpus', human.path), HUMAN_SAMPLE_MIN_WORDS),
      caption: `Opening paragraphs of ${human.title}, ${human.author}, ${human.date}. ${human.licence}.`,
    },
    corpus,
    facts: corpusFacts(corpus),
    manifest: manifest.files.map(({ id, kind, title, author, date, licence, url, words }) => ({ id, kind, title, author, date, licence, url: url ?? null, words })),
    caveat: corpus.caveat,
    inSample,
    npm: JSON.parse(read('scripts', 'npm-status.json')),
  };
}

export function renderDataJs(data) {
  return `// Generated by scripts/build-docs-data.mjs. Do not edit.\nexport const TELLS_DATA = ${JSON.stringify(data, null, 2)};\nif (typeof window !== 'undefined') window.TELLS_DATA = TELLS_DATA;\n`;
}

/** The generated pages, each with its computed regions by marker name. */
export const PAGES = ['index.html', 'rules.html'];

export function regions(data, name = 'index.html') {
  const text = data.sample.text;
  const report = analyze(text, FIXED);
  const c = data.corpus;
  if (name === 'rules.html') {
    return {
      rules: page.renderRulesIndex(),
      audit: page.renderAuditExample(text),
    };
  }
  return {
    install: `<code id="install-cmd">${page.esc(page.installCommand(data))}</code>`,
    hero: page.renderHero(report, text),
    'hero-caption': page.esc(data.sample.caption),
    anatomy: page.renderAnatomy(report, text),
    overlap: page.renderOverlap(report),
    // Comments are not parsed inside a textarea, so the markers sit outside the element.
    textarea: `<textarea id="input" data-sample spellcheck="false" aria-label="Text to check" aria-describedby="privacy" placeholder="Paste a paragraph or more.">${page.esc(text)}</textarea>`,
    mirror: page.renderMirror(report, text),
    results: page.renderTryResults(report),
    'limits-compact': page.renderLimitsCompact(),
    versus: page.renderVersus(report, text),
    'gap-head': page.renderGapHead(c),
    gap: page.renderGap(c),
    'corpus-notes': `<p class="observed">Observed ${page.esc(c.observedAt)} with tells ${page.esc(c.tool.version)}, ${c.files.length} files. Reproduce: <code>${page.esc(c.command.replace(/^tells/, 'node bin/tells.mjs'))}</code></p><p class="insample">${page.inlineMd(data.inSample)}</p><p class="caveat">${page.esc(data.caveat)}</p>`,
    'limits-statement': page.renderLimitsStatement(),
    use: page.renderUse(data),
  };
}

/**
 * The page's Content-Security-Policy, computed from the page.
 *
 * Every inline script is allowed by its own sha256 rather than by
 * 'unsafe-inline', so an injected <script> does not run. `base-uri 'none'`
 * and `object-src 'none'` are named because `default-src` does not cover
 * base-uri at all, and a <base> injection would repoint every relative
 * script path. style-src keeps 'unsafe-inline' because the page sets a
 * custom property through a style attribute, which a hash cannot cover.
 *
 * Recomputed on every build, so editing the inline script and forgetting the
 * hash makes `npm run check-docs-data` fail instead of breaking the page.
 */
export function cspFor(html) {
  const inline = [...html.matchAll(/<script(?![^>]*\ssrc=)[^>]*>([\s\S]*?)<\/script>/g)].map((m) => m[1]);
  const hashes = inline.map((s) => `'sha256-${createHash('sha256').update(s, 'utf8').digest('base64')}'`);
  return [
    "default-src 'self'",
    ["script-src 'self'", ...hashes].join(' '),
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    "font-src 'self'",
    "connect-src 'none'",
    "form-action 'none'",
    "base-uri 'none'",
    "object-src 'none'",
    // No frame-ancestors: a browser ignores it in a <meta> element and logs a
    // console error, and there is no server here to send a header.
  ].join('; ');
}

const CSP_META = /(<meta http-equiv="Content-Security-Policy" content=")[^"]*(">)/;

export function buildPage(html, data, file = 'index.html') {
  let out = html;
  for (const [name, body] of Object.entries(regions(data, file))) {
    const open = `<!-- gen:${name} -->`;
    const close = `<!-- /gen:${name} -->`;
    const a = out.indexOf(open);
    const b = out.indexOf(close);
    if (a < 0 || b < a) throw new Error(`docs/${file} has no ${name} region`);
    out = out.slice(0, a + open.length) + body + out.slice(b);
  }
  if (!CSP_META.test(out)) throw new Error(`docs/${file} has no Content-Security-Policy meta tag`);
  return out.replace(CSP_META, (_, a, b) => `${a}${cspFor(out)}${b}`);
}

function checkNpm(name) {
  const today = new Date();
  const checkedOn = `${today.getFullYear()}-${String(today.getMonth() + 1).padStart(2, '0')}-${String(today.getDate()).padStart(2, '0')}`;
  const status = { command: `npm view ${name}`, checkedOn, published: false, result: '' };
  try {
    const version = execSync(`npm view ${name} version`, { stdio: ['ignore', 'pipe', 'pipe'] }).toString().trim();
    Object.assign(status, { published: true, result: `version ${version}` });
  } catch (e) {
    const err = String(e.stderr ?? e.message);
    if (!/E404/.test(err)) throw new Error(`npm view did not answer with a version or a 404:\n${err}`);
    status.result = 'E404 (not in this registry)';
  }
  writeFileSync(NPM_STATUS, `${JSON.stringify(status, null, 2)}\n`);
  console.log(`npm: ${status.command} -> ${status.result}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--npm')) checkNpm(JSON.parse(read('package.json')).name);
  const data = buildData();
  const js = renderDataJs(data);
  const built = PAGES.map((f) => [f, buildPage(read('docs', f), data, f)]);
  if (process.argv.includes('--check')) {
    const stale = [js === read('docs', 'data.js') ? null : 'docs/data.js', ...built.map(([f, h]) => (h === read('docs', f) ? null : `docs/${f}`))].filter(Boolean);
    console.log(stale.length ? `stale: ${stale.join(', ')}. Run: npm run docs-data` : `docs/data.js and the computed regions of ${PAGES.map((f) => `docs/${f}`).join(', ')} are current`);
    process.exit(stale.length ? 1 : 0);
  }
  mkdirSync(join(ROOT, 'docs'), { recursive: true });
  writeFileSync(join(ROOT, 'docs', 'data.js'), js);
  for (const [f, h] of built) writeFileSync(join(ROOT, 'docs', f), h);
  console.log(`wrote docs/data.js (${Buffer.byteLength(js)} bytes, corpus observed ${data.corpus.observedAt}) and ${built.map(([f]) => `${Object.keys(regions(data, f)).length} regions of docs/${f}`).join(', ')}`);
}
